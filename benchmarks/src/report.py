"""
AxiomESG Benchmark Report Generator
=====================================

Reads the benchmark CSV and produces REPORT.md with:
- Variant comparison tables
- Per-section metric breakdowns
- Bootstrap confidence intervals
- Resolution plan delta summaries
- Key findings and recommendations

Usage:
    python -m benchmarks.src.report --csv benchmarks/results/axiomesg_benchmark_runs.csv
"""
from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

# Ensure imports work
_repo_root = str(Path(__file__).resolve().parents[2])
if _repo_root not in sys.path:
    sys.path.insert(0, _repo_root)

from benchmarks.src.utils import bootstrap_ci, format_ci, get_benchmark_logger

logger = get_benchmark_logger("report")


def _safe_mean(series) -> float:
    """Safe mean that handles empty series."""
    if len(series) == 0:
        return 0.0
    return float(series.mean())


def _safe_std(series) -> float:
    if len(series) == 0:
        return 0.0
    return float(series.std())


def generate_report(
    csv_path: str,
    config_path: str = "benchmarks/config/benchmark.yaml",
) -> str:
    """
    Generate REPORT.md from benchmark CSV.

    Returns path to the generated report.
    """
    import pandas as pd
    import numpy as np

    with open(config_path, "r") as f:
        config = yaml.safe_load(f)

    results_dir = config.get("output", {}).get("results_dir", "benchmarks/results")
    report_path = os.path.join(results_dir, config.get("output", {}).get("report_file", "REPORT.md"))

    df = pd.read_csv(csv_path)
    total_runs = len(df)

    # Separate scored vs skipped
    scored = df[
        (df["variant_skipped_reason"].isna() | (df["variant_skipped_reason"] == ""))
        & (df["error_message"].isna() | (df["error_message"] == ""))
    ].copy()
    skipped = df[df["variant_skipped_reason"].notna() & (df["variant_skipped_reason"] != "")].copy()
    errored = df[df["error_message"].notna() & (df["error_message"] != "")].copy()

    lines: List[str] = []

    # ---- Header ----
    lines.append("# AxiomESG Benchmark Report")
    lines.append("")
    lines.append("*Auto-generated by the AxiomESG benchmarking harness.*")
    lines.append("")
    lines.append("---")
    lines.append("")

    # ---- Executive Summary ----
    lines.append("## Executive Summary")
    lines.append("")
    lines.append(f"| Statistic | Value |")
    lines.append(f"|-----------|-------|")
    lines.append(f"| Total runs | {total_runs} |")
    lines.append(f"| Scored runs | {len(scored)} |")
    lines.append(f"| Skipped runs (missing deps) | {len(skipped)} |")
    lines.append(f"| Errored runs | {len(errored)} |")

    unique_variants = scored["variant_id"].nunique() if not scored.empty else 0
    unique_docs = scored["doc_id"].nunique() if not scored.empty else 0
    lines.append(f"| Unique variants | {unique_variants} |")
    lines.append(f"| Unique documents | {unique_docs} |")

    if not scored.empty:
        lines.append(f"| JSON parse success rate | {_safe_mean(scored['json_parse_success']):.3f} |")
        lines.append(f"| Schema valid rate | {_safe_mean(scored['schema_valid']):.3f} |")
        lines.append(f"| Overall strict F1 (mean) | {_safe_mean(scored['overall_strict_f1']):.3f} |")
        lines.append(f"| Overall relaxed F1 (mean) | {_safe_mean(scored['overall_relaxed_f1']):.3f} |")
        lines.append(f"| Grounded metric rate (mean) | {_safe_mean(scored['grounded_metric_rate']):.3f} |")
        lines.append(f"| Mean total latency (ms) | {_safe_mean(scored['total_latency_ms']):.1f} |")
    lines.append("")

    # ---- Skipped Variants ----
    if not skipped.empty:
        lines.append("## Skipped Variants")
        lines.append("")
        skip_reasons = skipped.groupby(["variant_id", "variant_skipped_reason"]).size().reset_index(name="count")
        lines.append("| Variant | Reason | Runs Skipped |")
        lines.append("|---------|--------|-------------|")
        for _, row in skip_reasons.iterrows():
            lines.append(f"| {row['variant_id']} | {row['variant_skipped_reason']} | {row['count']} |")
        lines.append("")

    if scored.empty:
        lines.append("> **No scored runs available for detailed analysis.**")
        _write_report(report_path, lines)
        return report_path

    # ---- Variant Comparison Table ----
    lines.append("## Variant Comparison")
    lines.append("")

    key_metrics = [
        ("overall_strict_f1", "Strict F1"),
        ("overall_relaxed_f1", "Relaxed F1"),
        ("grounded_metric_rate", "Grounded %"),
        ("schema_valid", "Schema Valid %"),
        ("evidence_hit_rate", "Evidence Hit"),
        ("total_latency_ms", "Latency (ms)"),
    ]

    header = "| Variant | Runs |"
    sep = "|---------|------|"
    for _, label in key_metrics:
        header += f" {label} |"
        sep += "------|"

    lines.append(header)
    lines.append(sep)

    variant_groups = scored.groupby("variant_id")
    for vid, group in sorted(variant_groups, key=lambda x: x[0]):
        row = f"| {vid} | {len(group)} |"
        for col, _ in key_metrics:
            if col == "total_latency_ms":
                row += f" {_safe_mean(group[col]):.0f} |"
            else:
                row += f" {_safe_mean(group[col]):.3f} |"
        lines.append(row)

    lines.append("")

    # ---- Per-Section Breakdown ----
    lines.append("## Per-Section Metric Breakdown")
    lines.append("")
    for section_prefix, section_label in [("env", "Environmental"), ("soc", "Social"), ("gov", "Governance")]:
        lines.append(f"### {section_label}")
        lines.append("")
        lines.append("| Variant | Strict P | Strict R | Strict F1 | Relaxed P | Relaxed R | Relaxed F1 |")
        lines.append("|---------|----------|----------|-----------|-----------|-----------|------------|")
        for vid, group in sorted(variant_groups, key=lambda x: x[0]):
            sp = _safe_mean(group[f"{section_prefix}_strict_precision"])
            sr = _safe_mean(group[f"{section_prefix}_strict_recall"])
            sf = _safe_mean(group[f"{section_prefix}_strict_f1"])
            rp = _safe_mean(group[f"{section_prefix}_relaxed_precision"])
            rr = _safe_mean(group[f"{section_prefix}_relaxed_recall"])
            rf = _safe_mean(group[f"{section_prefix}_relaxed_f1"])
            lines.append(f"| {vid} | {sp:.3f} | {sr:.3f} | {sf:.3f} | {rp:.3f} | {rr:.3f} | {rf:.3f} |")
        lines.append("")

    # ---- Bootstrap Confidence Intervals ----
    lines.append("## Bootstrap 95% Confidence Intervals")
    lines.append("")
    eval_config = config.get("evaluation", {})
    n_bootstrap = eval_config.get("bootstrap_n", 1000)
    ci_level = eval_config.get("bootstrap_ci", 0.95)

    ci_metrics = [
        ("overall_strict_f1", "Overall Strict F1"),
        ("overall_relaxed_f1", "Overall Relaxed F1"),
        ("grounded_metric_rate", "Grounded Metric Rate"),
        ("total_latency_ms", "Total Latency (ms)"),
    ]

    lines.append("| Variant | Metric | Mean [95% CI] |")
    lines.append("|---------|--------|---------------|")

    for vid, group in sorted(variant_groups, key=lambda x: x[0]):
        for col, label in ci_metrics:
            values = group[col].dropna().tolist()
            if values:
                mean, lower, upper = bootstrap_ci(values, n_bootstrap, ci_level)
                if col == "total_latency_ms":
                    ci_str = format_ci(mean, lower, upper, 1)
                else:
                    ci_str = format_ci(mean, lower, upper, 3)
                lines.append(f"| {vid} | {label} | {ci_str} |")
    lines.append("")

    # ---- Paired Comparisons ----
    lines.append("## Paired Comparisons (V0 vs V3 vs V4)")
    lines.append("")
    lines.append("Key comparisons between Baseline (V0), Heuristic AWFA (V3), and Real AWFA (V4).")
    lines.append("")

    comparison_variants = ["V0_BASELINE", "V3_FILTER_HEURISTIC_AWFA", "V4_FILTER_REAL_AWFA"]
    available_for_comparison = [v for v in comparison_variants if v in scored["variant_id"].values]

    if len(available_for_comparison) >= 2:
        lines.append("| Metric | " + " | ".join(available_for_comparison) + " |")
        lines.append("|--------|" + "|".join(["--------"] * len(available_for_comparison)) + "|")

        comp_metrics = [
            "overall_strict_f1", "overall_relaxed_f1", "grounded_metric_rate",
            "evidence_hit_rate", "recall_at_10", "recall_at_30", "recall_at_60",
            "compression_ratio", "dedup_rate", "total_latency_ms",
        ]

        for metric in comp_metrics:
            row = f"| {metric} |"
            for vid in available_for_comparison:
                vgroup = scored[scored["variant_id"] == vid]
                val = _safe_mean(vgroup[metric])
                if metric == "total_latency_ms":
                    row += f" {val:.0f} |"
                else:
                    row += f" {val:.3f} |"
            lines.append(row)
        lines.append("")

    # ---- Groundedness Analysis ----
    lines.append("## Groundedness & Hallucination Analysis")
    lines.append("")
    lines.append("| Variant | Grounded % | Unsupported % | Narrative Grounded % |")
    lines.append("|---------|-----------|--------------|---------------------|")
    for vid, group in sorted(variant_groups, key=lambda x: x[0]):
        gr = _safe_mean(group["grounded_metric_rate"])
        ur = _safe_mean(group["unsupported_metric_rate"])
        nr = _safe_mean(group["narrative_grounded_rate"])
        lines.append(f"| {vid} | {gr:.3f} | {ur:.3f} | {nr:.3f} |")
    lines.append("")

    # ---- Year/Unit Quality ----
    lines.append("## Year & Unit Quality")
    lines.append("")
    lines.append("| Variant | Missing Year % | Wrong Year % | Missing Unit % |")
    lines.append("|---------|---------------|-------------|---------------|")
    for vid, group in sorted(variant_groups, key=lambda x: x[0]):
        my = _safe_mean(group["missing_year_rate"])
        wy = _safe_mean(group["wrong_year_rate"])
        mu = _safe_mean(group["unit_missing_rate"])
        lines.append(f"| {vid} | {my:.3f} | {wy:.3f} | {mu:.3f} |")
    lines.append("")

    # ---- Efficiency Analysis ----
    lines.append("## Efficiency Analysis")
    lines.append("")
    lines.append("| Variant | Extract (ms) | Filter (ms) | Weight (ms) | Intelligence (ms) | Validate (ms) | Total (ms) |")
    lines.append("|---------|-------------|------------|------------|------------------|--------------|-----------|")
    for vid, group in sorted(variant_groups, key=lambda x: x[0]):
        lines.append(
            f"| {vid}"
            f" | {_safe_mean(group['extract_ms']):.0f}"
            f" | {_safe_mean(group['filter_ms']):.0f}"
            f" | {_safe_mean(group['weight_ms']):.0f}"
            f" | {_safe_mean(group['intelligence_ms']):.0f}"
            f" | {_safe_mean(group['validate_ms']):.0f}"
            f" | {_safe_mean(group['total_latency_ms']):.0f} |"
        )
    lines.append("")

    # ---- Document Type Analysis ----
    lines.append("## Document Type Analysis")
    lines.append("")
    lines.append("| Doc Type | Runs | Strict F1 | Relaxed F1 | Grounded % | Schema Valid % |")
    lines.append("|----------|------|-----------|-----------|-----------|---------------|")
    for dtype, dgroup in scored.groupby("doc_type"):
        lines.append(
            f"| {dtype}"
            f" | {len(dgroup)}"
            f" | {_safe_mean(dgroup['overall_strict_f1']):.3f}"
            f" | {_safe_mean(dgroup['overall_relaxed_f1']):.3f}"
            f" | {_safe_mean(dgroup['grounded_metric_rate']):.3f}"
            f" | {_safe_mean(dgroup['schema_valid']):.3f} |"
        )
    lines.append("")

    # ---- Augmentation Delta Summary ----
    if "augmentation_round" in scored.columns:
        augment_rounds = sorted(scored["augmentation_round"].dropna().unique())
        if len(augment_rounds) > 1:
            lines.append("## Augmentation Delta Summary")
            lines.append("")
            lines.append("Shows metric improvements across augmentation rounds.")
            lines.append("")

            base_round = scored[scored["augmentation_round"] == 0]
            for aug_round in augment_rounds:
                if aug_round == 0:
                    continue
                aug_data = scored[scored["augmentation_round"] == aug_round]
                lines.append(f"### Round {int(aug_round)}")
                lines.append("")
                lines.append(f"Additional docs: {aug_data['doc_id'].nunique()}")
                lines.append("")
                lines.append("| Metric | Before | After | Delta |")
                lines.append("|--------|--------|-------|-------|")
                for metric, label in [
                    ("overall_strict_f1", "Strict F1"),
                    ("overall_relaxed_f1", "Relaxed F1"),
                    ("grounded_metric_rate", "Grounded %"),
                    ("schema_valid", "Schema Valid %"),
                ]:
                    before = _safe_mean(base_round[metric])
                    # "After" = combination of base + augmentation
                    combined = pd.concat([base_round, aug_data])
                    after = _safe_mean(combined[metric])
                    delta = after - before
                    sign = "+" if delta >= 0 else ""
                    lines.append(f"| {label} | {before:.3f} | {after:.3f} | {sign}{delta:.3f} |")
                lines.append("")

    # ---- Key Findings ----
    lines.append("## Key Findings")
    lines.append("")

    if not scored.empty:
        best_variant = scored.groupby("variant_id")["overall_relaxed_f1"].mean().idxmax()
        best_f1 = scored.groupby("variant_id")["overall_relaxed_f1"].mean().max()
        lines.append(f"1. **Best overall variant**: `{best_variant}` with relaxed F1 = {best_f1:.3f}")

        # Check AWFA improvement
        if "V0_BASELINE" in scored["variant_id"].values and "V3_FILTER_HEURISTIC_AWFA" in scored["variant_id"].values:
            v0_f1 = _safe_mean(scored[scored["variant_id"] == "V0_BASELINE"]["overall_relaxed_f1"])
            v3_f1 = _safe_mean(scored[scored["variant_id"] == "V3_FILTER_HEURISTIC_AWFA"]["overall_relaxed_f1"])
            delta = v3_f1 - v0_f1
            lines.append(f"2. **Heuristic AWFA vs Baseline**: Relaxed F1 Δ = {delta:+.3f}")

        if "V4_FILTER_REAL_AWFA" in scored["variant_id"].values:
            v4_f1 = _safe_mean(scored[scored["variant_id"] == "V4_FILTER_REAL_AWFA"]["overall_relaxed_f1"])
            v4_gr = _safe_mean(scored[scored["variant_id"] == "V4_FILTER_REAL_AWFA"]["grounded_metric_rate"])
            lines.append(f"3. **Real AWFA** (V4): Relaxed F1 = {v4_f1:.3f}, Grounded = {v4_gr:.3f}")

        avg_latency = _safe_mean(scored["total_latency_ms"])
        lines.append(f"4. **Average latency**: {avg_latency:.0f} ms")

        # Groundedness summary
        avg_grounded = _safe_mean(scored["grounded_metric_rate"])
        lines.append(f"5. **Overall groundedness**: {avg_grounded:.3f}")

    lines.append("")

    # ---- Reproducibility Manifest ----
    lines.append("## Reproducibility")
    lines.append("")
    if not scored.empty:
        git_commit = scored["git_commit"].iloc[0] if "git_commit" in scored.columns else "unknown"
        lines.append(f"- Git commit: `{git_commit}`")
        lines.append(f"- Seed: {scored['seed'].min()} – {scored['seed'].max()}")
        lines.append(f"- LLM provider: {scored['llm_provider'].iloc[0]}")
        lines.append(f"- Model: {scored['llm_model_name'].iloc[0]}")
    lines.append(f"- CSV: `{csv_path}`")
    lines.append("")

    # ---- Generate Figures ----
    from benchmarks.src.figures import generate_figures
    figures_dir = os.path.join(results_dir, "figures")
    saved_figs = generate_figures(csv_path, figures_dir)
    
    if saved_figs:
        lines.append("## Visualizations")
        lines.append("")
        for fig_path in saved_figs:
            rel_path = os.path.relpath(fig_path, results_dir)
            lines.append(f"![{os.path.basename(fig_path)}]({rel_path})")
            lines.append("")

    _write_report(report_path, lines)
    logger.info(f"Report written to: {report_path}")
    return report_path


def _write_report(path: str, lines: List[str]) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    import argparse
    parser = argparse.ArgumentParser(description="Generate benchmark report")
    parser.add_argument("--csv", default="benchmarks/results/axiomesg_benchmark_runs.csv",
                        help="Path to benchmark CSV")
    parser.add_argument("--config", default="benchmarks/config/benchmark.yaml",
                        help="Path to benchmark config")
    args = parser.parse_args()

    generate_report(args.csv, args.config)


if __name__ == "__main__":
    main()
